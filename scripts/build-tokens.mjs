// Turns src/design-system/tokens.json into src/styles/tokens.css.
// Run with: npm run tokens (also runs before dev and build).
import { readFileSync, writeFileSync } from 'node:fs';

const tokens = JSON.parse(readFileSync(new URL('../src/design-system/tokens.json', import.meta.url), 'utf8'));

const isToken = (node) => node && typeof node === 'object' && '$value' in node;
const name = (path) => `--${path.join('-')}`;

// "{color.gray.200}" becomes var(--color-gray-200)
const alias = (value) =>
  typeof value === 'string' ? value.replace(/\{([^}]+)\}/g, (_, ref) => `var(${name(ref.split('.'))})`) : value;

const format = (token) => {
  const value = token.$value;
  if (Array.isArray(value)) return `cubic-bezier(${value.join(', ')})`;
  return alias(value);
};

const walk = (node, path, visit) => {
  for (const [key, child] of Object.entries(node)) {
    if (key.startsWith('$')) continue;
    if (isToken(child)) visit([...path, key], child);
    else if (child && typeof child === 'object') walk(child, [...path, key], visit);
  }
};

const base = [];
const add = (path, token) => {
  if (token.$type === 'typography' || isComposite(token)) {
    const v = token.$value;
    base.push(`  ${name([...path, 'size'])}: ${v.fontSize};`);
    base.push(`  ${name([...path, 'leading'])}: ${v.lineHeight};`);
    base.push(`  ${name([...path, 'tracking'])}: ${v.letterSpacing};`);
    base.push(`  ${name([...path, 'weight'])}: ${v.fontWeight};`);
  } else {
    base.push(`  ${name(path)}: ${format(token)};`);
  }
};
const isComposite = (token) => token.$value && typeof token.$value === 'object' && !Array.isArray(token.$value);

for (const [group, node] of Object.entries(tokens)) {
  if (group.startsWith('$') || group === 'theme') continue;
  walk(node, [group], add);
}

const mode = (values) => {
  const lines = [];
  walk(values, [], (path, token) => lines.push(`  ${name(path)}: ${format(token)};`));
  return lines.join('\n');
};

// Semantic colours are registered so the browser can animate them.
const registered = [];
walk(tokens.theme.light, [], (path, token) => {
  const initial = /gray\.(\d+)/.test(token.$value) ? tokens.color.gray[token.$value.match(/gray\.(\d+)/)[1]].$value : '#000';
  registered.push(`@property ${name(path)} { syntax: '<color>'; inherits: true; initial-value: ${initial}; }`);
});

const css = `/* Generated by scripts/build-tokens.mjs. Do not edit: change src/design-system/tokens.json instead. */
${registered.join('\n')}

@layer tokens {
:root {
${base.join('\n')}
}

:root:not([data-theme]),
:root[data-theme='light']:not([data-surface='inverse']),
:root[data-theme='dark'][data-surface='inverse'] {
  color-scheme: light;
${mode(tokens.theme.light)}
}

:root[data-theme='dark']:not([data-surface='inverse']),
:root[data-theme='light'][data-surface='inverse'] {
  color-scheme: dark;
${mode(tokens.theme.dark)}
}
}
`;

writeFileSync(new URL('../src/styles/tokens.css', import.meta.url), css);
console.log(`tokens.css written with ${base.length} base tokens`);
